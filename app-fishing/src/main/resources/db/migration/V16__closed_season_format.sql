-- 금어기 표기를 제철과 같은 형식으로 맞춘다.
--
-- 어종 상세의 규제 카드에서 두 줄이 나란히 나오는데 형식이 서로 달랐다:
--
--   제철    10월 ~ 12월      ← 한글 단위, 물결 양옆에 공백
--   금어기  05/01~05/31      ← 숫자 슬래시, 공백 없음, 앞자리 0
--
-- 같은 카드 안에서 같은 종류의 값(기간)이 두 형식으로 적히면 읽는 사람이 매번
-- 형식을 다시 해석해야 한다. 규제 정보라 특히 한눈에 들어와야 한다.
--
-- 컬럼이 그냥 표시용 문자열이라(파싱하는 코드가 없다) 값만 바꾸면 된다.
-- 앱에서 포맷하지 않고 여기서 고치는 이유: 형식이 셋뿐이라 파서를 두는 것보다
-- 원본을 맞추는 쪽이 확실하고, 나중에 어종이 늘어도 같은 형식으로 넣게 된다.

UPDATE fishing_species SET closed_season = '5월 1일 ~ 5월 31일'  WHERE closed_season = '05/01~05/31';
UPDATE fishing_species SET closed_season = '5월 1일 ~ 6월 10일'  WHERE closed_season = '05/01~06/10';
UPDATE fishing_species SET closed_season = '5월 11일 ~ 8월 31일' WHERE closed_season = '05/11~08/31';
