-- 영종도 선착장을 바다낚시지수 해역에 붙인다.
--
-- V6 이 이 포인트만 일부러 NULL 로 뒀다. 그때의 근거는 "가장 가까운 '인천항 서측(24km)' 이
-- 19.7km 밖 먼바다" 라는 것이었는데, V14 로 전국 포인트가 들어오면서 그 기준이 무너졌다:
--
--   돌산 갯바위  → 연도          28.2km   ← 영종도보다 멀다
--   사량도 옥동  → 욕지도        25.4km   ← 영종도보다 멀다
--   구룡포 방파제 → 포항         17.4km
--   영종도 선착장 → 인천항 서측  19.7km   ← 이것만 "멀다" 는 이유로 빠져 있었다
--
-- 붙이지 않은 대가가 컸다. 배치가 KHOA 를 안 부르니 수온·물때·주간지수를 못 채웠고,
-- FishingSpot.applyIndex 가 null 을 덮어쓰지 않는 탓에 **V2 시드값이 그대로 굳었다**:
--
--   수온 16.2℃         (같은 해역의 오늘 실측은 28.2℃ 다. 8월 말에 16.2℃ 는 나올 수 없다)
--   물때 '7물 · 만조 14:05'  (KHOA 는 '대조기' 처럼만 준다. 시안에서 온 표기다)
--
-- 게다가 이 포인트는 서해에서 id 가 가장 작아 **지역 선택 화면의 서해 대표값**이었다.
-- 8월 말 서해 카드에 16.2℃ 가 뜨던 게 이것 때문이다.
--
-- ⚠️ 이 해역은 어종을 '-' 하나로만 준다 (FishingIndexParser 가 걸러낸다).
--    그래서 추천 어종은 비어서 온다 — applyIndex 가 빈 목록으로 기존 값을 지우지 않게
--    같이 고쳤다. 시드의 우럭·광어·놀래미가 남는다.
--
-- ⚠️ 44번 '인천항 서측(24km)' 과 같은 해역을 보게 된다. 기장 학리·대변항이 '부산동부' 를
--    함께 보는 것과 같다 (V6 주석 참고) — 실제로 같은 바다라 값이 같은 게 맞다.

UPDATE fishing_spots SET khoa_place_name = '인천항 서측(24km)' WHERE id = 3;

-- ⚠️ 굳어 있는 수온·물때를 여기서 NULL 로 비우지 않는다. 처음엔 그러려 했는데,
--    비우면 첫 배치가 끝나기 전까지 SpotResponse.toDouble(null) 이 **0.0℃** 를 내보낸다.
--    8월의 16.2℃ 보다 0.0℃ 가 나쁘다 — 틀린 값이면서 정밀해 보이고, 물이 얼었다는 뜻이 된다.
--    배치가 한 번만 성공하면 시드값은 영영 사라지므로 비울 이유도 없다.
