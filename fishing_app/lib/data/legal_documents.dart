/// 가입 화면과 고객센터가 함께 쓰는 문서 하나.
class LegalDocument {
  const LegalDocument({
    required this.consentType,
    required this.title,
    required this.version,
    required this.body,
    this.required = true,
    this.summary,
  });

  /// 서버 `ConsentType` 과 **같은 코드**여야 한다. 어긋나면 400 이다.
  final String consentType;

  final String title;

  /// 사용자가 실제로 본 판. 동의 기록에 이 값이 그대로 남는다.
  final String version;

  final String body;

  /// 필수 동의인가. 선택 항목은 거부해도 가입이 된다.
  final bool required;

  /// 본문이 없는 항목(만 14세 확인처럼)은 체크박스 옆 한 줄이 전부다.
  final String? summary;

  bool get hasBody => body.isNotEmpty;
}

