package com.apa.auth.domain;

/**
 * {@code users.status}. 탈퇴는 행을 지우지 않고 상태로 남긴다 — 조과·게시글이 user_id 를 참조한다.
 *
 * <p>★ <b>그 덕분에 닉네임이 영영 풀리지 않는다.</b> `uq_users_nickname_lower` 가 탈퇴한 행의
 * 닉네임도 계속 붙잡고 있어서, 떠난 사람의 이름을 다른 사람이 가져갈 수 없다.
 * 게시글·댓글이 작성 시점 닉네임을 행에 박아 두는데({@code author_nickname}), 이름이 남에게
 * 넘어갈 수 있으면 <b>옛 글이 다른 사람 것처럼 보인다.</b> 이름을 회수하지 않는 것이 그걸 막는다.
 *
 * <p>레딧이 정확히 같은 규칙이다 — 삭제된 사용자명은 영구 은퇴하고 누구도 다시 못 쓴다.
 * (디시는 중복 확인된 <i>고정닉</i>과 아닌 <i>반고정닉</i>을 배지로 구분하고, 더쿠는 아예
 * 표시 신원을 없애 `무명의 더쿠`로만 둔다 — 셋 다 "자유롭게 개명하고 최신 이름을 보여준다" 를 안 한다.)
 *
 * <p>⚠️ <b>탈퇴를 하드 삭제로 바꾸지 말 것.</b> 행을 지우면 그 순간 이름이 풀린다.
 * 닉네임 변경 기능을 붙일 때도 <b>옛 이름은 회수하지 않는</b> 쪽으로 가야 한다.
 */
public enum UserStatus {
    ACTIVE,
    WITHDRAWN
}
